
#Multiple Assignment -> Allow to assign multiple variables at the same time in one line of code.

##Not using the multiple assignment.
name = "Luis"
age = 25
attractive = True

print(name)             #Print Luis
print(age)              #Print 25
print(attractive)       #Print True

Spongebob = 30
Patrick = 30
Sandy = 30
Squidward = 30

print(Spongebob)        #Print 30
print(Patrick)          #Print 30
print(Sandy)            #Print 30
print(Squidward)        #Print 30

##Using the multiple assignment.
name1, age1, attractive1 = "Luis", 25, True

print(name1)            #Print Luis
print(age1)             #Print 25
print(attractive1)      #Print True

Spongebob1 = Patrick1 = Sandy1 = Squidward1 = 30

print(Spongebob1)       #Print 30
print(Patrick1)         #Print 30
print(Sandy1)           #Print 30
print(Squidward1)       #Print 30
