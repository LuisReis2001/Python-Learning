
#Type Casting -> Converting a data type value to another data type.

x = 1       #int
y = 2.0     #float
z = "3"     #str

print(x)    #Print 1
print(y)    #Print 2.0
print(z)    #Print 3

#Casting the value to integer
y = int(y)

print(y)    #Print 2

z = int(z)
print(z * 3)    #Print 9

x = float(x)
print(x)        #Print 1.0

print("X is: " + str(x))    #Print X is: 1.0
