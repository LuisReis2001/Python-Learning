
import math

#Use of multiple methods for math problems.
pi = 3.14
x = 1
y = 2
z = 3

print(round(pi))        #Round the value to the closes int value.
print(math.ceil(pi))    #Round the number up to the closes next int value.
print(math.floor(pi))   #Round the number down to the closes previous int value.
print(abs(pi))          #Round the absolute value of the number distance of 0.
print(pow(pi, 2))       #Pow the value with base with the exponent.
print(math.sqrt(pi))    #Square root of a value.
print(max(x, y, z))     #Will find the maximum value of compared values.
print(min(x, y, z))     #Will find the minimum value of compared values.
