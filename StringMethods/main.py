
#Multiple different methods of strings.
name = "Luis"

print(name)                 #Print Luis
print(len(name))            #Print length will be 4
print(name.find("L"))       #Print the index where its find.
print(name.capitalize())    #Put the first letter in uppercase.
print(name.upper())         #Print the name in uppercase.
print(name.lower())         #Print the name in lowercase.
print(name.isdigit())       #Print the verification of being digit.
print(name.isalnum())       #Print the verification of being alphabetic letters.
print(name.count("L"))      #Print the amount of times the value on count is found.
print(name.replace("L", "T"))   #Print Tuis.
print(name * 3)             #Print the name 3 times.